  /// The state a point in India is in, by the nearest anchor; null if far from every anchor.
  static String? stateNear(double latitude, double longitude) {
    final scale = math.cos(latitude * math.pi / 180);
    double distance(Anchor a) {
      final dLat = a.latitude - latitude;
      final dLon = (a.longitude - longitude) * scale;
      return dLat * dLat + dLon * dLon;
    }
    Anchor? nearest;
    for (final a in anchors) {
      if (nearest == null || distance(a) < distance(nearest)) nearest = a;
    }
    if (nearest == null || distance(nearest) >= 3.5 * 3.5) return null;
    return nearest.state;
  }
